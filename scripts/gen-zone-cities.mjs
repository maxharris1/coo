import { readFileSync } from "node:fs";

const [tabPath] = process.argv.slice(2);
if (!tabPath)
  throw new Error(
    "usage: node scripts/gen-zone-cities.mjs <zone1970.tab> > src/lib/game/zoneCities.ts",
  );

function degrees(iso, degDigits) {
  const sign = iso[0] === "-" ? -1 : 1;
  const digits = iso.slice(1);
  const deg = Number(digits.slice(0, degDigits));
  const min = Number(digits.slice(degDigits, degDigits + 2));
  const sec = Number(digits.slice(degDigits + 2) || 0);
  return (sign * Math.round((deg + min / 60 + sec / 3600) * 1e4)) / 1e4;
}

function isSupported(tz) {
  try {
    new Intl.DateTimeFormat("en", { timeZone: tz });
    return true;
  } catch {
    return false;
  }
}

const rows = readFileSync(tabPath, "utf8")
  .split("\n")
  .filter((line) => line && !line.startsWith("#"))
  .map((line) => {
    const [, coords, tz] = line.split("\t");
    const [, lat, lon] = coords.match(/^([+-]\d+)([+-]\d+)$/);
    return { tz, lat: degrees(lat, 2), lon: degrees(lon, 3) };
  })
  .filter(({ tz }) => isSupported(tz));

process.stdout.write(
  [
    "// Generated by scripts/gen-zone-cities.mjs from tzdata zone1970.tab.",
    "type ZoneCity = { tz: string; lat: number; lon: number };",
    "",
    "export const zoneCities: readonly ZoneCity[] = [",
    ...rows.map(
      ({ tz, lat, lon }) =>
        `  { tz: ${JSON.stringify(tz)}, lat: ${lat}, lon: ${lon} },`,
    ),
    "];",
    "",
  ].join("\n"),
);
